// ============================================================
// regfile.v — レジスタファイル (32本 x 32bit)
// ============================================================
//
// 【構成】
//   - MIPS の汎用レジスタ $0〜$31 を保持する
//   - 読み出しポート: ra1(rs用), ra2(rt用), ra3(デバッグ用) の3ポート
//   - 書き込みポート: wa3/wd3 の1ポート (クロック立ち上がりで書き込み)
//
// 【$0 の扱い】
//   MIPS では $0 は常にゼロを返す (ハードワイヤードゼロ)。
//   読み出し時は ra==0 のとき 0 を返し、書き込み時は wa3!=0 を条件に
//   ガードすることで実現している。
//
// 【デバッグポート (ra3/rd3)】
//   AXI 経由で PS(ARM) 側から任意のレジスタ値を読み出すための
//   第3読み出しポート。halt中に使用する。

module regfile (
    input         clk,
    input         we3,        // 書き込み許可 (reg_write から接続)
    input  [4:0]  ra1,        // 読み出しアドレス1 (rs)
    input  [4:0]  ra2,        // 読み出しアドレス2 (rt)
    input  [4:0]  ra3,        // デバッグ用読み出しアドレス
    input  [4:0]  wa3,        // 書き込みアドレス (write_reg から接続)
    input  [31:0] wd3,        // 書き込みデータ (write_data から接続)
    output [31:0] rd1,        // 読み出しデータ1 (ALU入力Aへ)
    output [31:0] rd2,        // 読み出しデータ2 (ALU入力B or sw データへ)
    output [31:0] rd3         // デバッグ用読み出しデータ
);

    reg [31:0] rf [0:31];

    // シミュレーション用初期化 (FPGAでは電源投入時の値は不定)
    integer i;
    initial begin
        for (i = 0; i < 32; i = i + 1)
            rf[i] = 32'b0;
    end

    // 書き込み: クロック立ち上がりで実行。$0 (wa3==0) への書き込みは無視
    always @(posedge clk) begin
        if (we3 && wa3 != 5'b0)
            rf[wa3] <= wd3;
    end

    // 読み出し: 組み合わせ回路 (非同期)。$0 は常にゼロを返す
    assign rd1 = (ra1 == 5'b0) ? 32'b0 : rf[ra1];
    assign rd2 = (ra2 == 5'b0) ? 32'b0 : rf[ra2];
    assign rd3 = (ra3 == 5'b0) ? 32'b0 : rf[ra3];

endmodule
