// ============================================================
// imem.v — 命令メモリ (デュアルポートRAM, 256ワード x 32bit)
// ============================================================
//
// 【デュアルポート構成】
//   ポートA (MIPS側): PC から命令をフェッチする (読み出し専用, 非同期)
//   ポートB (PS側):   ARM から AXI 経由でプログラムを書き込む (書き込み専用)
//
// 【アドレス変換】
//   MIPS の PC はバイトアドレスだが、メモリはワード(4バイト)単位。
//   addr_a[9:2] の8ビットをワードアドレスとして使用する。
//     例: PC=0x00 → mem[0], PC=0x04 → mem[1], PC=0x08 → mem[2]
//
// 【容量】
//   256ワード x 4バイト = 1024バイト (1KB)
//   PC が 0x400 を超えるとアドレスが循環するため、テストプログラムは
//   末尾に無限ループ (j 自身) を入れて PC を停止させること

module imem (
    // ポートA: MIPS側 命令フェッチ (読み出し専用, 非同期)
    input  [31:0] addr_a,   // PC (バイトアドレス)
    output [31:0] instr,    // フェッチした命令

    // ポートB: PS側 プログラムロード (書き込み専用, 同期)
    input         clk_b,
    input         we_b,
    input  [7:0]  addr_b,   // ワードアドレス (0〜255)
    input  [31:0] din_b     // 書き込む命令データ
);

    reg [31:0] mem [0:255];

    // ポートA: PC[9:2] でワードアドレスに変換して読み出す
    assign instr = mem[addr_a[9:2]];

    // ポートB: ARM側からクロック同期で命令を書き込む
    always @(posedge clk_b) begin
        if (we_b)
            mem[addr_b] <= din_b;
    end

endmodule
