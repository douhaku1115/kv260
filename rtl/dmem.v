// ============================================================
// dmem.v — データメモリ (256ワード x 32bit RAM)
// ============================================================
//
// 【役割】
//   lw/sw 命令で使用するデータ格納用メモリ。
//   imem (命令メモリ) とは独立したアドレス空間を持つ。
//
// 【読み書きタイミング】
//   読み出し: 組み合わせ回路 (非同期) — 単一サイクル設計のため、
//             同一クロック内で ALU 結果アドレスを受けてすぐに値を出力する
//   書き込み: クロック立ち上がりで mem_write=1 のとき実行 (sw 命令)
//
// 【アドレス変換】
//   MIPS のアドレスはバイト単位。imem と同様に addr[9:2] でワード変換。
//     例: addi $2, $0, 0; sw $1, 0($2) → addr=0x00 → mem[0]

module dmem (
    input         clk,
    input         mem_write,  // 書き込み許可 (sw 命令のとき 1)
    input  [31:0] addr,       // バイトアドレス (ALU結果 = ベース + オフセット)
    input  [31:0] write_data, // 書き込みデータ (rt レジスタ値)
    output [31:0] read_data   // 読み出しデータ (lw でレジスタに書き戻す)
);

    reg [31:0] mem [0:255];

    // 読み出し: 非同期 (lw は同一クロック内で完結)
    assign read_data = mem[addr[9:2]];

    // 書き込み: 同期 (sw: クロック立ち上がりで確定)
    always @(posedge clk) begin
        if (mem_write)
            mem[addr[9:2]] <= write_data;
    end

endmodule
